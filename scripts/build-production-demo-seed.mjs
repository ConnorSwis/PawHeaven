// Turns supabase/seed-lively.sql into a version safe to run against the hosted demo database:
// members get delivered+name@resend.dev addresses (Resend's test inbox, so reminder and notification
// emails never bounce), staff-authored rows are credited to a real staff account, and animals that only
// exist in the local seed are swapped for ones in the hosted shelter.
//   node scripts/build-production-demo-seed.mjs <staff-user-uuid>   writes .cache/production-demo-seed.sql
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const staffId = process.argv[2];
if (!/^[0-9a-f-]{36}$/i.test(staffId ?? '')) throw new Error('Usage: node scripts/build-production-demo-seed.mjs <staff-user-uuid>');
const root = fileURLToPath(new URL('..', import.meta.url));
let sql = readFileSync(`${root}supabase/seed-lively.sql`, 'utf8');

const swap = (from, to) => { if (!sql.includes(from)) throw new Error(`Expected to find: ${from}`); sql = sql.replaceAll(from, to); };
swap("lower(first || '.' || last) || '@pawheaven.local' as email", "'delivered+' || lower(first || '.' || last) || '@resend.dev' as email");
swap('a1000000-0000-0000-0000-000000000002', staffId);
for (const [local, hosted] of [["'Arlo'", "'Tahoe'"], ["'Wren'", "'Rigby'"], ["'Poppy'", "'Nita'"], ["'Juniper'", "'Chesney'"], ["'Miso'", "'Carlton'"], ["'Cleo'", "'Izzy Lightwood'"]]) {
  if (sql.includes(local)) sql = sql.replaceAll(local, hosted);
}
// The hosted database already has a few visit times; skip any the seed would overlap.
swap('    from days, times\n    returning id, starts_at, ends_at', '    from days, times\n    on conflict do nothing\n    returning id, starts_at, ends_at');
sql = `-- Generated by scripts/build-production-demo-seed.mjs from supabase/seed-lively.sql. Demo data only.\n${sql}`;
mkdirSync(`${root}.cache`, { recursive: true });
writeFileSync(`${root}.cache/production-demo-seed.sql`, sql);
console.log(`Wrote .cache/production-demo-seed.sql (${sql.split('\n').length} lines).`);
